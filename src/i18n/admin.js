function translate(value, params = {}) {
  if (typeof value !== 'string') {
    return value;
  }
  const template = language.value === 'fr' ? fr[value] || value : value;
  return template.replace(/\{(\w+)\}/g, (_, key) => params[key] ?? '');
}

function translateConfig(value, seen = new WeakMap()) {
  if (Array.isArray(value)) {
    return value.map((item) => translateConfig(item, seen));
  }
  if (!value || typeof value !== 'object' || value instanceof Date) {
    return value;
  }
  if (seen.has(value)) {
    return seen.get(value);
  }

  const copy = {};
  seen.set(value, copy);
  for (const [key, child] of Object.entries(value)) {
    copy[key] = DISPLAY_KEYS.has(key) && typeof child === 'string' ? translate(child) : translateConfig(child, seen);
  }
  return copy;
}

function enumLabel(value) {
  if (value === null || value === undefined || value === '') {
    return '-';
  }
  const raw = String(value);
  return translate(raw).replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase());
}

function setLanguage(next) {
  language.value = next === 'fr' ? 'fr' : 'en';
  localStorage.setItem(STORAGE_KEY, language.value);
}

function toggleLanguage() {
  setLanguage(language.value === 'fr' ? 'en' : 'fr');
}

export function useAdminI18n() {
  return {
    enumLabel,
    language,
    languageLabel: computed(() => (language.value === 'fr' ? 'English' : 'Français')),
    localeCode: computed(() => (language.value === 'fr' ? 'fr-FR' : 'en')),
    setLanguage,
    t: translate,
    toggleLanguage,
    translateConfig,
  };
}
